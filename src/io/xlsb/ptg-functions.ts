// Indexed by `iftab`; a hole is an index the specification does not define.
//
// Assigned into a bare array rather than built with `flat()`, so the gaps are genuinely absent
// entries rather than present-and-undefined ones, which is what lets the transcription test tell the
// two apart.
const TABLE: (FunctionEntry | undefined)[] = [];
for (const [start, entries] of RUNS) {
  entries.forEach((entry, offset) => {
    TABLE[start + offset] = entry;
  });
}

/** The built-in function an `iftab` index names, or `undefined` if the index names none. */
export function builtinFunctionAt(index: number): FunctionEntry | undefined {
  return TABLE[index];
}

/** Look up a built-in function name by its `iftab` index, or `undefined` if the index names none. */
export function functionNameFor(index: number): string | undefined {
  return TABLE[index]?.[0];
}

// Exported for the transcription test beside this file, and for nothing else. Six hundred names typed
// out of a normative table have exactly one failure mode, a slip in the typing, and it is invisible at
// runtime: a name in the wrong slot still decodes, just to a different function, for every formula
// citing that index. Nothing checked the transcription, so the test asserts what the specification
// says about the table's shape rather than recomputing it from the runs it is written as.
export const FTAB: readonly (FunctionEntry | undefined)[] = TABLE;
