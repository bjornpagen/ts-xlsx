// The built-in functions a formula can pass as a value, the way `SUM` is passed in `BYROW(A1:A3,SUM)`,
// keyed by uppercased name. Excel stores such a name under `_xleta.`, as `_xlfn.BYROW(A1:A3,_xleta.SUM)`;
// the same name stored bare is a reference to a defined name called `SUM`, which Excel shows as `#NAME?`
// when the workbook defines none. `formula.ts` is the single place that applies and removes the prefix.
//
// No specification lists these, so the list is Excel's own answer. Excel Desktop 16.0 (build 20326) was
// given `=MAP(1,<name>)` for every name in the [MS-XLS] function table, the future-function registry,
// the Analysis ToolPak and the members of its own `WorksheetFunction` object, and saved the workbook;
// the names it wrote with the prefix are the ones here. What it left bare is as telling: the XLM macro
// functions of the function table (`GOTO`, `GET.CELL`), `TRUE`, `FALSE` and `LOG10`, which read as
// literals and a cell, and the four post-2007 names it also calls without a prefix (`NETWORKDAYS.INTL`,
// `WORKDAY.INTL`, `ISO.CEILING`, `ECMA.CEILING`).
//
// Every future function is a value but the six in `NOT_VALUES`, so what is written out below is only
// the functions older than that registry, and a name added to it is a value from the day it is added.

