// The future functions Excel left bare. LAMBDA and LET bind names rather than compute a value, and the
// other four are Python and Power Query plumbing.
export const NOT_VALUES: ReadonlySet<string> = new Set([
  'LAMBDA',
  'LET',
  'PYTHON_STR',
  'PYTHON_TYPE',
  'PYTHON_TYPENAME',
  'QUERYSTRING',
]);

export const OLDER_FUNCTION_VALUES: readonly string[] = OLDER_FUNCTIONS.trim().split(/\s+/);

/** Every built-in function Excel stores under `_xleta.` when a formula passes it as a value. */
export const FUNCTION_VALUE_NAMES: ReadonlySet<string> = new Set([
  ...OLDER_FUNCTION_VALUES,
  ...[...FUTURE_FUNCTION_PREFIXES.keys()].filter((name) => !NOT_VALUES.has(name)),
]);
